raw_log = [
    "  A-101   12.450   Day  ",
    "A-102  12.400   Day",
    " A-103  12.510 Day  ",
    "A-104 12.380   Day",
    "  A-105   12.480   Day",
    "A-106  12.550 Day ",
    " A-107 12.420   Day",
    "  A-108 12.450   Day  ",
    "A-109   12.390  Day",
    "  A-110 12.460   Day"
]

# Container choices justified per Container Discipline rule
accepted_diameters = []  # list: preserves repeated measurements for accurate calculation
rework_diameters = []    # list: preserves duplicates for rework total tracking
scrap_diameters = []     # list: preserves duplicates for scrap statistics
scrapped_part_codes = [] # list: maintains order of failed parts during audit

# Tolerances: Accepted (12.40 - 12.50), Rework (12.38 - 12.39), Scrap (<12.38 or >12.50)
for line in raw_log:
    code, dia_str, shift = line.split()
    dia = float(dia_str)

    if 12.40 <= dia <= 12.50:
        accepted_diameters.append(dia)
    elif 12.38 <= dia < 12.40:
        rework_diameters.append(dia)
    else:
        scrap_diameters.append(dia)
        scrapped_part_codes.append(code)

print(f"Accepted count: {len(accepted_diameters)}")
print(f"Rework count: {len(rework_diameters)}")
print(f"Scrap count: {len(scrap_diameters)}")
#IT-8
if accepted_diameters:
    accepted_avg = sum(accepted_diameters) / len(accepted_diameters)
    print(f"Accepted average: {accepted_avg:.3f}")

print("Scrapped Part Codes:", scrapped_part_codes)

day_log = [
    "A-101 12.45 Day", "A-102 12.35 Day", "A-103 12.55 Day",
    "A-104 12.42 Day", "A-105 12.38 Day"
]

night_log = [
    "B-201 12.44 Night", "A-102 12.36 Night", "B-203 12.52 Night",
    "A-103 12.58 Night", "B-205 12.41 Night"
]

def parse_shift(log):
    accepted = []   # list: keeps duplicate readings for calculating accept rate accurately
    scrapped = []   # list: keeps log of scrapped codes prior to set analysis

    for line in log:
        code, dia_str, _ = line.split()
        dia = float(dia_str)
        if 12.40 <= dia <= 12.50:
            accepted.append(dia)
        else:
            scrapped.append(code)

    accept_rate = (len(accepted) / len(log)) * 100
    return accept_rate, scrapped

day_rate, day_scrap_list = parse_shift(day_log)
night_rate, night_scrap_list = parse_shift(night_log)

print(f"Day Shift Accept Rate: {day_rate:.1f}%")
print(f"Night Shift Accept Rate: {night_rate:.1f}%")
#IT-6
# Using sets for uniqueness and set operations
day_scrap_set = set(day_scrap_list)      # set: eliminates duplicates to isolate unique part codes
night_scrap_set = set(night_scrap_list)  # set: eliminates duplicates to isolate unique part codes

both_shifts = day_scrap_set & night_scrap_set
unique_to_one = day_scrap_set ^ night_scrap_set

print("Scrapped in both shifts:", both_shifts)
print("Scrapped in only one shift:", unique_to_one)
