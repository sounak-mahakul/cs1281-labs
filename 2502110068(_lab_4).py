mode = (
    input("Choose mode ('halt' or 'skip'): ").strip().lower()
)
inspected_count = 0

for i in range(100):
    diameter = round(random.uniform(24.90, 25.10), 2)
    inspected_count += 1

    # Bin logic
    if 24.95 <= diameter <= 25.05:
        bin_category = "ACCEPT"
    elif (24.92 <= diameter < 24.95) or (25.05 < diameter <= 25.08):
        bin_category = "REWORK"
    else:
        bin_category = "SCRAP"

    if bin_category == "SCRAP":
        if mode == "halt":
            print(
                f"SCRAP encountered at part {inspected_count} ({diameter} mm). Halting batch!"
            )
            break
        elif mode == "skip":
            print(
                f"Part {inspected_count}: {diameter} mm -> SCRAP (Skipped)"
            )
            continue

    print(f"Part {inspected_count}: {diameter} mm -> {bin_category}")

print(f"\nTotal parts inspected before stop/end: {inspected_count}")

