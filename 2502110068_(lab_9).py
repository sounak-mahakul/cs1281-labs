import os

os.makedirs("data", exist_ok=True)
log_path = os.path.join("data", "shift_log.txt")
report_path = os.path.join("data", "report.txt")
rejects_path = os.path.join("data", "rejects.csv")

valid_records = []
rejects = []

# Read and process input
if os.path.exists(log_path):
    with open(log_path, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, start=1):
            line_clean = line.strip()
            if not line_clean:
                continue

            parts = [p.strip() for p in line_clean.split(",")]

            # Basic validation: expects exactly 3 fields (part code, temperature, shift)
            if len(parts) < 3:
                rejects.append(f"{line_num},{line_clean},Insufficient fields")
                continue

            code, temp_str, shift = parts[0], parts[1], parts[2]

            # Validate temperature conversion
            try:
                temp = float(temp_str)
            except ValueError:
                rejects.append(f"{line_num},{line_clean},Invalid temperature format")
                continue

            valid_records.append({"code": code, "temp": temp, "shift": shift})

# Write the human report
with open(report_path, "w", encoding="utf-8") as f:
    f.write(f"{'PART CODE':<12} | {'TEMP (°C)':<10} | {'SHIFT':<10}\n")
    f.write("-" * 38 + "\n")
    for r in valid_records:
        f.write(f"{r['code']:<12} | {r['temp']:<10.2f} | {r['shift']:<10}\n")

# Write the rejects log
with open(rejects_path, "w", encoding="utf-8") as f:
    f.write("LineNumber,RawLine,Reason\n")
    for rej in rejects:
        f.write(rej + "\n")

print(f"Pipeline executed. Valid records processed: {len(valid_records)}, Rejects logged: {len(rejects)}")

import os
import re

log_path = os.path.join("data", "shift_log.txt")

# Regex pattern to match part codes like PE-0137, allowing flexible whitespace around commas
pattern = re.compile(r'^(PE-\d+)\s*,\s*([+-]?\d*\.\d+|\d+)\s*,\s*([A-Za-z]+)')

valid_records = []
rejects = []

if os.path.exists(log_path):
    with open(log_path, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, start=1):
            line_clean = line.strip()
            if not line_clean:
                continue

            match = pattern.match(line_clean)
            if match:
                code, temp_str, shift = match.groups()
                valid_records.append({"code": code, "temp": float(temp_str), "shift": shift})
            else:
                rejects.append(f"{line_num},{line_clean},Regex mismatch")

print(f"Regex successfully parsed {len(valid_records)} records out of {len(valid_records) + len(rejects)} total lines.")

import os
import glob
from datetime import datetime

data_dir = "data"
os.makedirs(data_dir, exist_ok=True)

history_path = os.path.join(data_dir, "run_history.csv")

# Initialize run history file with headers if it doesn't exist
if not os.path.exists(history_path):
    with open(history_path, "w", encoding="utf-8") as f:
        f.write("Timestamp,FileName,RecordsProcessed,Rejects\n")

txt_files = glob.glob(os.path.join(data_dir, "*.txt"))
total_plant_records = 0

for file_path in txt_files:
    filename = os.path.basename(file_path)
    if filename in ["report.txt", "summary_report.txt"]:
        continue

    processed = 0
    rejects_count = 0

    with open(file_path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                if "PE-" in line and "," in line:
                    processed += 1
                else:
                    rejects_count += 1

    # Append run history entry
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(history_path, "a", encoding="utf-8") as f:
        f.write(f"{timestamp},{filename},{processed},{rejects_count}\n")

    total_plant_records += processed

# Create plant-wide summary
summary_path = os.path.join(data_dir, "summary_report.txt")
with open(summary_path, "w", encoding="utf-8") as f:
    f.write(f"PLANT BATCH SUMMARY - {datetime.now().strftime('%Y-%m-%d')}\n")
    f.write(f"Total files processed: {len(txt_files)}\n")
    f.write(f"Total valid records across plant: {total_plant_records}\n")

print("Batch processing complete. History updated and summary generated.")