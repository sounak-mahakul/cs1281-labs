def inspect(dia):
    """Takes a diameter and returns a bin label: 'accept', 'rework', or 'scrap'."""
    if dia > 25.05:
        return "rework"
    elif dia < 24.95:
        return "scrap"
    else:
        return "accept"


def tally(labels):
    """Takes a list of bin labels and returns a count dictionary."""
    counts = {"accept": 0, "rework": 0, "scrap": 0}
    for label in labels:
        if label in counts:
            counts[label] += 1
    return counts


def report(shift, counts):
    """Takes a shift name and counts dictionary, and returns a formatted line."""
    return f"{shift.upper()}   accept {counts['accept']} rework {counts['rework']} scrap {counts['scrap']}"
