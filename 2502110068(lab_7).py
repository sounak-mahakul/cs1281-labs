import random

class BatchPress:
    def __init__(self, model, capacity_tonnes):
        self.__model = model
        self.__capacity_tonnes = capacity_tonnes
        self.__successful_jobs = 0
        self.__failed_jobs = 0

    def operate(self, force_requested):
        if force_requested > self.__capacity_tonnes or force_requested <= 0:
            self.__failed_jobs += 1
        else:
            self.__successful_jobs += 1

    def status(self):
        total = self.__successful_jobs + self.__failed_jobs
        return (f"--- Shift Report: {self.__model} ---\n"
                f"Attempted: {total}\n"
                f"Success: {self.__successful_jobs}\n"
                f"Failed: {self.__failed_jobs}")

batch_machine = BatchPress("Delta", 250)
jobs = [random.randint(50, 350) for _ in range(10)]

for job in jobs:
    batch_machine.operate(job)

print(batch_machine.status())
