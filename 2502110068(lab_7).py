import random

class FleetPress:
    def __init__(self, model, capacity_tonnes):
        self.model = model
        self.capacity_tonnes = capacity_tonnes
        self.parts_made = 0
        self.is_free = True

    def operate(self, force):
        # Simulate being busy and processing the part
        self.is_free = False
        if force <= self.capacity_tonnes:
            self.parts_made += 1
        self.is_free = True

def main():
    fleet = [
        FleetPress("Light-Press", 100),
        FleetPress("Medium-Press", 200),
        FleetPress("Heavy-Press", 400)
    ]

    # Generate a batch of 20 random jobs
    jobs = [random.randint(50, 350) for _ in range(20)]

    for job in jobs:
        # Allocate to the first free machine capable of handling the load
        for machine in fleet:
            if machine.is_free and job <= machine.capacity_tonnes:
                machine.operate(job)
                break
#IT-6
    # Plant Report
    print("=== FINAL PLANT REPORT ===")
    plant_total = 0

    for machine in fleet:
        print(f"{machine.model}: {machine.parts_made} parts")
        plant_total += machine.parts_made

    print(f"Plant Total: {plant_total} parts")

    # Find the busiest machine using max() with a lambda key
    busiest = max(fleet, key=lambda m: m.parts_made)
    print(f"Busiest Machine: {busiest.model} ({busiest.parts_made} parts)")

if __name__ == "__main__":
    main()
