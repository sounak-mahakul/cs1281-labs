class GuardedPress:
    def __init__(self, model, capacity_tonnes):
        self.__model = model
        self.__capacity_tonnes = capacity_tonnes
        self.__cycles_completed = 0

    def __str__(self):
        return f"Nameplate: {self.__model} | Capacity: {self.__capacity_tonnes}T"

    def operate(self, force_requested):
        if force_requested > self.__capacity_tonnes:
            print(f"GUARD TRIPPED: {force_requested}T exceeds {self.__model}'s {self.__capacity_tonnes}T limit.")
        elif force_requested <= 0:
            print("GUARD TRIPPED: Force must be greater than 0.")
        else:
            self.__cycles_completed += 1
            print(f"Cycle successful at {force_requested}T.")

    def status(self):
        return f"Status [{self.__model}]: {self.__cycles_completed} successful cycles."

machine = GuardedPress("Gamma", 150)
machine.operate(200) # Refused
machine.operate(100) # Accepted
print(machine.status())
